#!/usr/bin/env node
/**
 * T19 — build the inline Lucide sprite used by layout.js.
 * Lucide is ISC; WhatsApp comes from Simple Icons (CC0).
 *
 * Run with: node tests/build-icons.mjs
 */

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lucideRoot = path.join(projectRoot, "node_modules", "lucide-static", "icons");
const simpleRoot = path.join(projectRoot, "node_modules", "simple-icons", "icons");
const layoutPath = path.join(projectRoot, "site", "assets", "js", "layout.js");

const ICONS = {
  "icon-paw": "paw-print",
  "icon-calendar": "calendar",
  "icon-clock": "clock",
  "icon-phone": "phone",
  "icon-map-pin": "map-pin",
  "icon-syringe": "syringe",
  "icon-scissors": "scissors",
  "icon-stethoscope": "stethoscope",
  "icon-heart-pulse": "heart-pulse",
  "icon-alert": "triangle-alert",
  "icon-check": "check",
  "icon-arrow": "arrow-right",
  "icon-arrow-left": "arrow-left",
  "icon-menu": "menu",
  "icon-close": "x",
  "icon-sun": "sun",
  "icon-moon": "moon",
  "icon-chevron-left": "chevron-left",
  "icon-chevron-right": "chevron-right",
  "icon-chevron-down": "chevron-down",
  "icon-star": "star",
  "icon-heart": "heart",
  "icon-mail": "mail",
  "icon-download": "download",
  "icon-info": "info",
  "icon-user": "user"
};

function inner(svg) {
  return svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<svg[^>]*>/, "")
    .replace(/<\/svg>/, "")
    .replace(/<title>[\s\S]*?<\/title>/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

async function main() {
  const symbols = [];
  for (const [id, file] of Object.entries(ICONS)) {
    const svg = await readFile(path.join(lucideRoot, `${file}.svg`), "utf8");
    symbols.push(
      `<symbol id="${id}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner(svg)}</symbol>`
    );
  }

  const whatsapp = await readFile(
    path.join(simpleRoot, "whatsapp.svg"),
    "utf8"
  );
  symbols.push(
    `<symbol id="icon-whatsapp" viewBox="0 0 24 24" fill="currentColor">${inner(whatsapp)}</symbol>`
  );

  const sprite =
    '<svg class="icon-sprite" aria-hidden="true" focusable="false" width="0" height="0">' +
    symbols.join("") +
    "</svg>";

  let source = await readFile(layoutPath, "utf8");
  const start = source.indexOf("  var ICON_SPRITE =");
  const end = source.indexOf("\n\n  /* Theme", start);
  if (start === -1 || end === -1) {
    throw new Error("Could not find ICON_SPRITE in layout.js");
  }

  const replacement =
    "  /* Generated by tests/build-icons.mjs from Lucide (ISC) and Simple Icons (CC0). */\n" +
    "  var ICON_SPRITE = " +
    JSON.stringify(sprite) +
    ";";
  source = source.slice(0, start) + replacement + source.slice(end);
  await writeFile(layoutPath, source);
  console.log(
    `Wrote ${symbols.length} symbols from Lucide and Simple Icons into layout.js`
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
